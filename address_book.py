import pandas as pd
# Начальные данные
columns = ["ФИО", "Адрес", "Телефон", "Дата рождения"]
users = [{"ФИО": "Лёха Пупкин", "Адрес": "Москва", "Телефон": "111-111", "Дата рождения": "12.01.1990"}, {"ФИО": "Тоха Чёрный", "Адрес": "Сочи", "Телефон": "222-222", "Дата рождения": "17.05.1995"}]
df = pd.DataFrame(users, columns=columns)
# Бесконечный цикл для меню программы
while True:
    print("ТЕКУЩАЯ ТАБЛИЦА")
    print(df)
    print("Что вы хотите сделать?")
    print("1 - Добавить пользователя")
    print("2 - Редактировать данные")
    print("3 - Удалить пользователя")
    print("4 - Выйти из программы")
    
    choice = input("Выберите действие (1-4): ")
    
    if choice == "1":
        print("Добавление данных")
        name = input("Введите ФИО: ")
        address = input("Введите адрес: ")
        phone = input("Введите телефон: ")
        birthday = input("Введите дату рождения: ")
        
        # Добавление новой строки в конец
        df.loc[len(df)] = [name, address, phone, birthday]
        print("Пользователь успешно добавлен!")
        
    elif choice == "2":
        print("Редактирование данных")
        row = int(input("Введите номер строки: "))
        col = input("Введите название колонки (ФИО/Адрес/Телефон/Дата рождения): ")
        value = input("Введите новое значение: ")
        # Проверяем, правильный ли индекс и колонка
        if row in df.index and col in df.columns:
            df.at[row, col] = value
            print("Данные изменены!")
        else:
            print("Ошибка: неверная строка или колонка!")           
    elif choice == "3":
        print("Удаление данных")
        row = int(input("Введите номер строки для удаления: "))
        if row in df.index:
            df = df.drop(row)
            df = df.reset_index(drop=True)  # Пересчитываем индексы с нуля
            print("Строка удалена!")
        else:
            print("Ошибка: строки с таким номером нет!")          
    elif choice == "4":
        print("Программа завершена. До свидания!")
        break     
    else:
        print("Неверный ввод! Выберите пункт от 1 до 4.")